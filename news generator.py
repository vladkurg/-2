import os
import anthropic

client = anthropic.Anthropic(api_key=os.getenv("ANTHROPIC_API_KEY"))

NEWS_TOPICS = [
    "советы по уходу за коврами в домашних условиях",
    "как часто нужно стирать ковры",
    "виды загрязнений ковров и методы их удаления",
    "преимущества профессиональной чистки ковров",
    "как выбрать ковёр для дома",
    "сезонный уход за коврами",
    "как сохранить цвет ковра после стирки",
    "вредители ковров и как с ними бороться",
    "экологичные методы чистки ковров",
    "ковры и аллергия — что нужно знать",
]

_topic_index = 0

async def generate_news():
    global _topic_index
    topic = NEWS_TOPICS[_topic_index % len(NEWS_TOPICS)]
    _topic_index += 1

    prompt = f"""Ты — контент-менеджер компании "Стирка ковров Донецк". 
Напиши короткую, интересную новость или полезный совет для Telegram-канала на тему: "{topic}".

Требования:
- Длина: 100-200 слов
- Живой, дружелюбный тон
- В конце добавь призыв обратиться в "Стирка ковров Донецк"
- Используй 1-2 подходящих эмодзи
- Без хэштегов
- Только текст поста, никаких пояснений"""

    message = client.messages.create(
        model="claude-sonnet-4-20250514",
        max_tokens=500,
        messages=[{"role": "user", "content": prompt}]
    )
    return message.content[0].text
